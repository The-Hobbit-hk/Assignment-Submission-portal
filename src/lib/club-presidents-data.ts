export function presidentEmail(record: ClubPresidentRecord): string {
  if (record.email?.trim()) {
    return record.email.trim().toLowerCase();
  }
  const id = record.riMemberId ?? record.clubRiId;
  return `president.${id}@club.rotaract3131.org`;
}

export function splitPresidentName(fullName: string) {
  const clean = fullName.replace(/^Rtr\.?\s*/i, "").trim();
  const parts = clean.split(/\s+/).filter(Boolean);
  if (parts.length <= 1) {
    return { firstName: clean, lastName: "" };
  }
  return {
    firstName: parts.slice(0, -1).join(" "),
    lastName: parts[parts.length - 1],
  };
}

export function presidentBio(record: ClubPresidentRecord): string | undefined {
  const parts: string[] = ["Club President"];
  if (record.instagram) {
    parts.push(`Instagram: @${record.instagram.replace(/^@/, "")}`);
  }
  return parts.join(" · ");
}
